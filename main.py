#!/usr/bin/env python3
"""Make the coolest art -- entry program v6 (Python 3.13, standard library only).

"A Child, a UFO, and the Village on the Hill": a small child stands on a
hilltop village at night and looks up as a little green alien descends
inside a beam of light from a huge glowing UFO hovering in front of them.
A few small houses with warm lit windows, pine trees, a winding path and
fireflies fill the hill below. Flat woodblock / ukiyo-e style, bold
limited palette (navy + gold + red + cream), with a pale-green alien as
the only new accent.

Deliberately DIFFERENT from the competition's top-1 image ("Mending the
Moon"): no moon at all, no cracks or kintsugi, no scaffolding, no crane,
no detached fragment, no sea; the cosmic object is a UFO disc with a
light beam, not a moon; the story is a first-contact encounter in a
village, not a repair crew. Also different from our own v5 ("Ironing
the Sea"): no red sun, no sea, no wave, no boat, no iron, no workers.
The top-1 reference was looked at only to know what to avoid; every
pixel here is generated by this program's own drawing code -- shapes,
gradients, curves, seeded randomness. No pixels were copied, embedded
or traced.

Deterministic: fixed seed, no clock, no network, no unseeded randomness.
Writes /output/entry.png (or $MAKEFUN_OUTPUT_DIR/entry.png), 1024x1024,
well under 1 MiB. PNG encoder written by hand with stdlib zlib + struct.
"""

