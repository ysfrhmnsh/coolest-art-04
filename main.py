import random
import struct
import zlib

W = H = 1024
SEED = 20261113

# ---------------------------------------------------------------- palette
SKY_TOP = (9, 17, 44)
SKY_MID = (13, 26, 60)
SKY_LOW = (19, 38, 78)
GOLD = (232, 169, 28)
GOLD_CORE = (255, 217, 74)
GOLD_DEEP = (190, 130, 18)
RED = (206, 59, 29)
RED_DARK = (178, 46, 22)
SIL = (10, 18, 48)          # child silhouette, dark navy
CREAM = (242, 232, 208)     # smoke / steam
HILL = (10, 18, 44)         # hill silhouette
HOUSE = (18, 30, 64)        # house walls
ROOF = (160, 44, 26)        # roof tiles, dark red
