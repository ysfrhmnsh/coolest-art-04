# ---------------------------------------------------------------- helpers
def clamp(v, lo=0, hi=255):
    return lo if v < lo else hi if v > hi else v


def lerp(a, b, t):
    return a + (b - a) * t


def lerp3(c1, c2, t):
    return (lerp(c1[0], c2[0], t), lerp(c1[1], c2[1], t), lerp(c1[2], c2[2], t))


def smooth(t):
    t = 0.0 if t < 0.0 else 1.0 if t > 1.0 else t
    return t * t * (3.0 - 2.0 * t)


# ---------------------------------------------------------------- PNG writer
def _png_chunk(typ, data):
    c = struct.pack(">I", len(data)) + typ + data
    return c + struct.pack(">I", zlib.crc32(typ + data) & 0xFFFFFFFF)


def _filter_row(filter_type, row, prev):
    n = len(row)
    out = bytearray(n)
    if filter_type == 0:  # None
        return bytes(row)
    if filter_type == 1:  # Sub
        for i in range(n):
            a = row[i - 3] if i >= 3 else 0
            out[i] = (row[i] - a) & 0xFF
    elif filter_type == 2:  # Up
        for i in range(n):
            out[i] = (row[i] - prev[i]) & 0xFF
    elif filter_type == 3:  # Average
        for i in range(n):
            a = row[i - 3] if i >= 3 else 0
            out[i] = (row[i] - ((a + prev[i]) >> 1)) & 0xFF
    else:  # Paeth
        for i in range(n):
            a = row[i - 3] if i >= 3 else 0
            b = prev[i]
            c = prev[i - 3] if i >= 3 else 0
            p = a + b - c
            pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
            pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
            out[i] = (row[i] - pr) & 0xFF
    return bytes(out)


def _filter_score(frow):
    return sum(b if b < 128 else 256 - b for b in frow)


def write_png(path, px, w, h):
    """px: bytearray of RGB triples, w*h*3. Adaptive per-row filter."""
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    raw = bytearray()
    prev = bytes(w * 3)
    stride = w * 3
    for y in range(h):
        row = bytes(px[y * stride:(y + 1) * stride])
        best_f, best_s = 0, None
        for f in (0, 1, 2, 3, 4):
            cand = _filter_row(f, row, prev)
            s = _filter_score(cand)
            if best_s is None or s < best_s:
                best_f, best_s, best_row = f, s, cand
        raw.append(best_f)
        raw += best_row
        prev = row
    data = b"\x89PNG\r\n\x1a\n"
    data += _png_chunk(b"IHDR", ihdr)
    data += _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    data += _png_chunk(b"IEND", b"")
    with open(path, "wb") as fh:
        fh.write(data)
    return len(data)


# ---------------------------------------------------------------- drawing primitives
def set_px(px, x, y, col):
    if 0 <= x < W and 0 <= y < H:
        i = (y * W + x) * 3
        px[i], px[i + 1], px[i + 2] = col[0], col[1], col[2]


def blend_px(px, x, y, col, a):
    if 0 <= x < W and 0 <= y < H and a > 0.0:
        i = (y * W + x) * 3
        px[i] = int(lerp(px[i], col[0], a))
        px[i + 1] = int(lerp(px[i + 1], col[1], a))
        px[i + 2] = int(lerp(px[i + 2], col[2], a))


def fill_circle(px, cx, cy, r, col, alpha=1.0):
    cx = int(cx)
    cy = int(cy)
    r = int(r)
    if r <= 0:
        return
    for y in range(max(0, cy - r), min(H - 1, cy + r) + 1):
        dy = y - cy
        dx = int(math.sqrt(max(0, r * r - dy * dy)))
        x0 = max(0, cx - dx)
        x1 = min(W - 1, cx + dx)
        for x in range(x0, x1 + 1):
            if alpha >= 1.0:
                set_px(px, x, y, col)
            else:
                blend_px(px, x, y, col, alpha)


def fill_ellipse(px, cx, cy, rx, ry, col, alpha=1.0):
    cx = int(cx)
    cy = int(cy)
    rx = int(rx)
    ry = int(ry)
    if rx <= 0 or ry <= 0:
        return
    for y in range(max(0, cy - ry), min(H - 1, cy + ry) + 1):
        dy = (y - cy) / float(ry)
        dx = int(rx * math.sqrt(max(0.0, 1.0 - dy * dy)))
        x0 = max(0, cx - dx)
        x1 = min(W - 1, cx + dx)
        for x in range(x0, x1 + 1):
            if alpha >= 1.0:
                set_px(px, x, y, col)
            else:
                blend_px(px, x, y, col, alpha)


def fill_poly(px, pts, col, alpha=1.0):
    """Scanline fill for a (possibly concave) polygon. pts = [(x, y), ...]."""
    if len(pts) < 3:
        return
    ys = [p[1] for p in pts]
    ya = max(0, int(min(ys)))
    yb = min(H - 1, int(max(ys)) + 1)
    n = len(pts)
    for y in range(ya, yb + 1):
        xs = []
        for k in range(n):
            ax, ay = pts[k]
            bx, by = pts[(k + 1) % n]
            if (ay <= y < by) or (by <= y < ay):
                t = (y - ay) / float(by - ay)
                xs.append(ax + t * (bx - ax))
        xs.sort()
        for k in range(0, len(xs) - 1, 2):
            xa = max(0, int(math.ceil(xs[k])))
            xb = min(W - 1, int(math.floor(xs[k + 1])))
            for x in range(xa, xb + 1):
                if alpha >= 1.0:
                    set_px(px, x, y, col)
                else:
                    blend_px(px, x, y, col, alpha)


def stroke(px, x0, y0, x1, y1, w, col, alpha=1.0):
    """Thick line: stamp circles along the segment."""
    dist = math.hypot(x1 - x0, y1 - y0)
    steps = max(1, int(dist / max(1.0, w * 0.45)))
    r = w / 2.0
    for k in range(steps + 1):
        t = k / float(steps)
        fill_circle(px, int(x0 + (x1 - x0) * t), int(y0 + (y1 - y0) * t),
                    r, col, alpha)


def tube(px, pts, radii, col, alpha=1.0):
    """Tapering tube through pts with per-point radii (arc-length interp)."""
    seg = []
    total = 0.0
    for k in range(len(pts) - 1):
        d = math.hypot(pts[k + 1][0] - pts[k][0], pts[k + 1][1] - pts[k][1])
        seg.append(d)
        total += d
    n = max(2, int(total / 3.0))
    for s in range(n + 1):
        target = total * s / float(n)
        acc = 0.0
        for k in range(len(pts) - 1):
            if acc + seg[k] >= target or k == len(pts) - 2:
                f = 0.0 if seg[k] == 0 else (target - acc) / seg[k]
                f = max(0.0, min(1.0, f))
                x = pts[k][0] + (pts[k + 1][0] - pts[k][0]) * f
                y = pts[k][1] + (pts[k + 1][1] - pts[k][1]) * f
                r = radii[k] + (radii[k + 1] - radii[k]) * f
                fill_circle(px, int(x), int(y), r, col, alpha)
                break
            acc += seg[k]

# ---------------------------------------------------------------- scene pieces
def cloud_band(px, x0, x1, y_base, amp, thick, col):
    """Flat stylised cloud ribbon: wavy top and bottom edges."""
    top, bot = [], []
    n = max(4, int((x1 - x0) / 9.0))
    for k in range(n + 1):
        x = x0 + (x1 - x0) * k / float(n)
        t = k / float(n)
        y_top = y_base + amp * math.sin(t * math.pi * 2.0 + 0.6) \
            + 0.45 * amp * math.sin(t * math.pi * 5.0 + 2.0)
        y_bot = y_base + thick + 0.6 * amp * math.sin(t * math.pi * 2.0 + 2.6) \
            + 0.3 * amp * math.sin(t * math.pi * 4.0 + 0.4)
        top.append((x, y_top))
        bot.append((x, y_bot))
    fill_poly(px, top + bot[::-1], col)


def house(px, x, base, w, h, rng):
    """One small village house: dark walls, red triangular roof, two
    warm lit windows, a door, a chimney with a wisp of smoke. Base at
    (x, base) is the bottom-left corner; the house is planted slightly
    into the hill so it reads as sitting on the crest."""
    # walls
    fill_poly(px, [(x, base - h), (x + w, base - h),
                   (x + w, base), (x, base)], HOUSE)
    # roof: triangle with a small overhang
    apex = (x + w // 2, base - h - int(w * 0.42))
    fill_poly(px, [(x - 6, base - h), (x + w + 6, base - h), apex], ROOF)
    # roof shading: darker lower band
    fill_poly(px, [(x - 6, base - h), (x + w + 6, base - h),
                   (x + w + 2, base - h - 10), (x - 2, base - h - 10)],
              RED_DARK, 0.5)
    # chimney on the roof's right slope + smoke puffs
    chx = x + int(w * 0.72)
    fill_poly(px, [(chx, base - h - 34), (chx + 12, base - h - 34),
                   (chx + 12, base - h - 8), (chx, base - h - 8)], HOUSE)
    for k, (dx, dy, r, a) in enumerate(((6, -46, 7, 0.35),
                                        (12, -60, 9, 0.28),
                                        (20, -76, 11, 0.20))):
        fill_circle(px, chx + dx, base - h + dy, r, CREAM, a)
    # two warm windows
    for wx in (x + int(w * 0.18), x + int(w * 0.58)):
        fill_poly(px, [(wx, base - h + 18), (wx + 16, base - h + 18),
                       (wx + 16, base - h + 36), (wx, base - h + 36)],
                  WINDOW)
        # window cross-frame
        stroke(px, wx + 8, base - h + 18, wx + 8, base - h + 36, 2, HOUSE)
        stroke(px, wx, base - h + 27, wx + 16, base - h + 27, 2, HOUSE)
    # door
    fill_poly(px, [(x + int(w * 0.42), base - 26),
                   (x + int(w * 0.58), base - 26),
                   (x + int(w * 0.58), base),
                   (x + int(w * 0.42), base)], HILL)


def pine(px, x, base, s):
    """Dark pine tree, base at (x, base), height ~ s."""
    # trunk
    fill_poly(px, [(x - 4, base - 14), (x + 4, base - 14),
                   (x + 3, base), (x - 3, base)], TREE)
    # three stacked triangles, widest at the bottom
    for k, (wy, ww) in enumerate(((0.62, 0.62), (0.38, 0.46), (0.16, 0.30))):
        yb = base - 12 - s * wy
        yt = base - 12 - s * (wy + 0.30)
        w2 = s * ww * 0.5
        fill_poly(px, [(x - w2, yb), (x + w2, yb), (x, yt)], TREE)


def child(px, x, feet):
    """The small child, seen from behind, feet at (x, feet), ~145 px
    tall: dark silhouette, red cap and scarf, one arm raised pointing
    up toward the UFO, gold rim light on the side the UFO shines on.
    Drawn larger than a real child would be at this distance, so the
    story's tiny human still reads clearly against the dark hill."""
    s = 1.25
    # soft shadow under the feet
    fill_ellipse(px, x, feet + 2, int(46 * s), int(8 * s), (0, 0, 0), 0.25)
    # legs
    stroke(px, x - 8 * s, feet - 46 * s, x - 14 * s, feet, 7 * s, SIL)
    stroke(px, x + 8 * s, feet - 46 * s, x + 14 * s, feet, 7 * s, SIL)
    # coat: little trapezoid, wider at the hem
    fill_poly(px, [(x - 15 * s, feet - 78 * s), (x + 15 * s, feet - 78 * s),
                   (x + 20 * s, feet - 44 * s), (x - 20 * s, feet - 44 * s)],
              SIL)
    # head (back view) + red cap on top
    fill_circle(px, x, feet - 96 * s, 17 * s, RED_DARK)
    fill_circle(px, x, feet - 90 * s, 15 * s, SIL)
    fill_circle(px, x, feet - 110 * s, 4 * s, RED)  # cap knob
    # scarf: red band across the neck + a tail fluttering right
    stroke(px, x - 16 * s, feet - 78 * s, x + 16 * s, feet - 78 * s, 8 * s,
           RED)
    stroke(px, x + 14 * s, feet - 76 * s, x + 26 * s, feet - 56 * s, 6 * s,
           RED)
    # left arm hanging down at the side
    stroke(px, x - 14 * s, feet - 74 * s, x - 22 * s, feet - 40 * s, 6 * s,
           SIL)
    # right arm raised, pointing up-right toward the UFO
    stroke(px, x + 13 * s, feet - 74 * s, x + 46 * s, feet - 132 * s, 7 * s,
           SIL)
    fill_circle(px, x + 48 * s, feet - 134 * s, 5 * s, SIL)
    # gold edge on the raised arm so the pointing gesture reads
    stroke(px, x + 16 * s, feet - 76 * s, x + 47 * s, feet - 130 * s,
           2.5, GOLD, 0.55)
    # gold rim light on the UFO-facing side (head, coat, leg)
    stroke(px, x + 16 * s, feet - 100 * s, x + 17 * s, feet - 78 * s,
           2.5, GOLD, 0.8)
    stroke(px, x + 17 * s, feet - 76 * s, x + 20 * s, feet - 46 * s,
           2.5, GOLD, 0.7)
    fill_circle(px, x + 14 * s, feet - 98 * s, 4, GOLD, 0.6)


def beam(px, x0, x1, y_top, y_bot, col, alpha):
    """Translucent light-beam trapezoid, narrow at the UFO, wide at the
    hill. Drawn as two stacked trapezoids for a soft falloff edge."""
    mid0 = (x0 + x1) / 2.0
    hw_top = (x1 - x0) / 2.0
    hw_bot = hw_top * 1.9
    fill_poly(px, [(x0, y_top), (x1, y_top),
                   (mid0 + hw_bot, y_bot), (mid0 - hw_bot, y_bot)],
              col, alpha)


def ufo(px, cx, cy):
    """The giant glowing UFO: pale-gold dome, wide gold disc with a
    darker underside, a row of glowing lights along the rim, a tiny
    antenna. The disc is ~430 px wide -- the cosmic object of the
    picture, dwarfing the child below. The dome is kept low and flat
    so the wide disc, not the dome, is the dominant shape."""
    # underside (darker, slightly lower and narrower)
    fill_ellipse(px, cx, cy + 14, 200, 30, GOLD_DEEP)
    # main disc
    fill_ellipse(px, cx, cy, 215, 40, GOLD)
    # bright sheen stripe across the disc front
    fill_ellipse(px, cx - 20, cy - 8, 180, 22, GOLD_CORE, 0.35)
    # dome: low and flat, sitting on top of the disc
    fill_ellipse(px, cx, cy - 24, 85, 38, DOME)
    fill_ellipse(px, cx - 22, cy - 36, 26, 13, GOLD_CORE, 0.5)
    # antenna on the dome
    stroke(px, cx, cy - 60, cx, cy - 84, 4, GOLD)
    fill_circle(px, cx, cy - 88, 6, GOLD_CORE)
    # row of glowing lights along the disc rim
    for k in range(6):
        lx = cx - 170 + k * 68
        fill_circle(px, lx, cy + 18, 13, GOLD, 0.30)
        fill_circle(px, lx, cy + 18, 7, GOLD_CORE)
    # small portholes on the dome
    for k in range(3):
        px0 = cx - 40 + k * 40
        fill_circle(px, px0, cy - 20, 5, GOLD_DEEP, 0.8)


def alien(px, cx, cy):
    """The little green alien descending inside the beam, ~90 px tall:
    round head with two big dark eyes, thin body, arms held slightly
    out as if floating, lit by the beam's gold glow."""
    # soft glow around the figure
    fill_ellipse(px, cx, cy, 70, 95, GOLD, 0.12)
    # legs (thin, dangling)
    stroke(px, cx - 6, cy + 18, cx - 12, cy + 44, 5, ALIEN)
    stroke(px, cx + 6, cy + 18, cx + 12, cy + 44, 5, ALIEN)
    # body
    tube(px, [(cx, cy - 8), (cx, cy + 20)], [11, 9], ALIEN)
    # belly shade
    fill_ellipse(px, cx + 4, cy + 10, 6, 10, ALIEN_DARK, 0.35)
    # arms held slightly out and up (floating)
    stroke(px, cx - 8, cy - 2, cx - 30, cy - 16, 5, ALIEN)
    stroke(px, cx + 8, cy - 2, cx + 30, cy - 16, 5, ALIEN)
    fill_circle(px, cx - 31, cy - 17, 4, ALIEN)
    fill_circle(px, cx + 31, cy - 17, 4, ALIEN)
    # head
    fill_circle(px, cx, cy - 26, 24, ALIEN)
    # big dark eyes (tall ovals), with a tiny gold catchlight each
    fill_ellipse(px, cx - 10, cy - 30, 7, 11, EYE)
    fill_ellipse(px, cx + 10, cy - 30, 7, 11, EYE)
    fill_circle(px, cx - 12, cy - 34, 2.5, GOLD_CORE, 0.9)
    fill_circle(px, cx + 8, cy - 34, 2.5, GOLD_CORE, 0.9)
    # tiny mouth + head highlight from the beam
    stroke(px, cx - 4, cy - 12, cx + 4, cy - 12, 2, ALIEN_DARK, 0.8)
    fill_circle(px, cx - 10, cy - 42, 5, GOLD_CORE, 0.25)

# ---------------------------------------------------------------- renderer
CREST = [(0, 690), (140, 640), (300, 615), (470, 645),
         (640, 610), (800, 640), (940, 605), (1024, 630)]


def render():
    px = bytearray(W * H * 3)
    rng = random.Random(SEED + 7)

    # ---- sky: vertical navy gradient over the whole canvas ----
    for y in range(H):
        t = y / float(H)
        if t < 0.5:
            base = lerp3(SKY_TOP, SKY_MID, t / 0.5)
        else:
            base = lerp3(SKY_MID, SKY_LOW, (t - 0.5) / 0.5)
        off = y * W * 3
        for x in range(W):
            i = off + x * 3
            px[i] = int(base[0])
            px[i + 1] = int(base[1])
            px[i + 2] = int(base[2])

    # ---- stars: small gold dots in the sky ----
    for _ in range(55):
        x = rng.randrange(20, 1004)
        y = rng.randrange(14, 480)
        r = 1.5 + 1.5 * rng.random()
        fill_circle(px, x, y, r, GOLD_CORE, 0.35 + 0.5 * rng.random())

    # ---- gold cloud bands (flat, woodblock style) ----
    cloud_band(px, 60, 380, 88, 12, 24, GOLD)
    cloud_band(px, 780, 1024, 140, 10, 20, GOLD)
    cloud_band(px, 40, 300, 420, 8, 16, GOLD)

    # ---- the light beam: wide translucent gold cone from the UFO
    # down to the hill (drawn before the UFO, so the disc covers its
    # top; drawn before the hill, so the hill clips its foot) ----
    beam(px, 620, 700, 265, 635, GOLD, 0.15)
    beam(px, 640, 685, 265, 635, GOLD_CORE, 0.18)

    # ---- the giant UFO hovering upper-right ----
    ufo(px, 660, 225)

    # ---- the little alien descending inside the beam ----
    alien(px, 665, 480)

    # ---- the hill: rolling silhouette across the lower third ----
    fill_poly(px, CREST + [(1024, H), (0, H)], HILL)
    # thin gold line along the crest, so hill and sky separate
    tube(px, CREST, [2.5] * len(CREST), GOLD, 0.35)

    # ---- the village: five small houses along the crest ----
    house(px, 70, 668, 100, 64, rng)
    house(px, 215, 642, 90, 58, rng)
    house(px, 430, 672, 110, 64, rng)
    house(px, 775, 668, 95, 60, rng)
    house(px, 895, 632, 80, 50, rng)

    # ---- pine trees between the houses ----
    pine(px, 55, 692, 110)
    pine(px, 355, 640, 95)
    pine(px, 735, 660, 105)

    # ---- winding path of gold dots from the village to the child ----
    for k in range(13):
        t = k / 12.0
        x = int(470 - 170 * t + 20 * math.sin(t * math.pi * 1.5))
        y = int(700 + 205 * t)
        fill_circle(px, x, y, 3, GOLD, 0.5)

    # ---- fireflies drifting over the hill ----
    for _ in range(12):
        x = rng.randrange(80, 980)
        y = rng.randrange(720, 960)
        if 250 < x < 360 and 780 < y < 920:
            continue  # keep the child silhouette clear
        fill_circle(px, x, y, 2 + int(2 * rng.random()), GOLD_CORE,
                    0.4 + 0.4 * rng.random())

    # ---- the small child in the foreground, looking up ----
    child(px, 300, 905)

    # ---- grass tufts along the bottom edge ----
    for (gx, gy) in ((120, 1002), (520, 1012), (700, 996), (900, 1006)):
        for dx in (-10, 0, 10):
            stroke(px, gx, gy, gx + dx, gy - 22 - abs(dx), 2.5, TREE)

    return px


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    px = render()
    path = os.path.join(out_dir, "entry.png")
    size = write_png(path, px, W, H)
    print(f"wrote {path} ({size} bytes, {W}x{H})")


if __name__ == "__main__":
    main()
